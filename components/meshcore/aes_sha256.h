inline uint32_t rotr(uint32_t x, uint32_t n) { return (x >> n) | (x << (32 - n)); }

inline void transform(Ctx *ctx, const uint8_t data[64]) {
  uint32_t m[64];
  for (int i = 0; i < 16; i++)
    m[i] = (data[i*4] << 24) | (data[i*4+1] << 16) | (data[i*4+2] << 8) | data[i*4+3];
  for (int i = 16; i < 64; i++) {
    uint32_t s0 = rotr(m[i-15], 7) ^ rotr(m[i-15], 18) ^ (m[i-15] >> 3);
    uint32_t s1 = rotr(m[i-2], 17) ^ rotr(m[i-2], 19) ^ (m[i-2] >> 10);
    m[i] = m[i-16] + s0 + m[i-7] + s1;
  }
  uint32_t a=ctx->state[0],b=ctx->state[1],c=ctx->state[2],d=ctx->state[3];
  uint32_t e=ctx->state[4],f=ctx->state[5],g=ctx->state[6],h=ctx->state[7];
  for (int i = 0; i < 64; i++) {
    uint32_t S1 = rotr(e,6) ^ rotr(e,11) ^ rotr(e,25);
    uint32_t ch = (e & f) ^ ((~e) & g);
    uint32_t temp1 = h + S1 + ch + K[i] + m[i];
    uint32_t S0 = rotr(a,2) ^ rotr(a,13) ^ rotr(a,22);
    uint32_t maj = (a & b) ^ (a & c) ^ (b & c);
    uint32_t temp2 = S0 + maj;
    h=g; g=f; f=e; e=d+temp1; d=c; c=b; b=a; a=temp1+temp2;
  }
  ctx->state[0]+=a; ctx->state[1]+=b; ctx->state[2]+=c; ctx->state[3]+=d;
  ctx->state[4]+=e; ctx->state[5]+=f; ctx->state[6]+=g; ctx->state[7]+=h;
}

inline void init(Ctx *ctx) {
  ctx->state[0]=0x6a09e667; ctx->state[1]=0xbb67ae85; ctx->state[2]=0x3c6ef372; ctx->state[3]=0xa54ff53a;
  ctx->state[4]=0x510e527f; ctx->state[5]=0x9b05688c; ctx->state[6]=0x1f83d9ab; ctx->state[7]=0x5be0cd19;
  ctx->bitlen = 0; ctx->buffer_len = 0;
}

inline void update(Ctx *ctx, const uint8_t *data, size_t len) {
  for (size_t i = 0; i < len; i++) {
    ctx->buffer[ctx->buffer_len++] = data[i];
    if (ctx->buffer_len == 64) {
      transform(ctx, ctx->buffer);
      ctx->bitlen += 512;
      ctx->buffer_len = 0;
    }
  }
}

inline void final(Ctx *ctx, uint8_t out[32]) {
  size_t i = ctx->buffer_len;
  ctx->bitlen += (uint64_t)ctx->buffer_len * 8;
  ctx->buffer[i++] = 0x80;
  if (i > 56) {
    while (i < 64) ctx->buffer[i++] = 0;
    transform(ctx, ctx->buffer);
    i = 0;
  }
  while (i < 56) ctx->buffer[i++] = 0;
  for (int j = 7; j >= 0; j--) ctx->buffer[i++] = (uint8_t)(ctx->bitlen >> (j * 8));
  transform(ctx, ctx->buffer);
  for (int j = 0; j < 4; j++) {
    for (int k = 0; k < 8; k++)
      out[k*4+j] = (uint8_t)(ctx->state[k] >> (24 - j*8));
  }
}

inline void hash(const uint8_t *data, size_t len, uint8_t out[32]) {
  Ctx ctx; init(&ctx); update(&ctx, data, len); final(&ctx, out);
}

inline void hmac(const uint8_t *key, size_t key_len, const uint8_t *data, size_t data_len, uint8_t out[32]) {
  uint8_t k0[64];
  memset(k0, 0, sizeof(k0));
  if (key_len > 64) { hash(key, key_len, k0); } else { memcpy(k0, key, key_len); }

  uint8_t ipad[64], opad[64];
  for (int i = 0; i < 64; i++) { ipad[i] = k0[i] ^ 0x36; opad[i] = k0[i] ^ 0x5c; }

  Ctx ctx;
  init(&ctx);
  update(&ctx, ipad, 64);
  update(&ctx, data, data_len);
  uint8_t inner[32];
  final(&ctx, inner);

  init(&ctx);
  update(&ctx, opad, 64);
  update(&ctx, inner, 32);
  final(&ctx, out);
}

