static const uint8_t Rcon[11] = {
  0x8d,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36
};

struct Ctx {
  uint8_t round_key[176];  // 11 * 16 pour AES-128
};

inline void key_expansion(Ctx *ctx, const uint8_t *key) {
  uint8_t *rk = ctx->round_key;
  memcpy(rk, key, 16);
  uint8_t tempa[4];
  for (unsigned i = 4; i < 44; i++) {
    memcpy(tempa, rk + 4 * (i - 1), 4);
    if (i % 4 == 0) {
      // RotWord
      uint8_t t = tempa[0];
      tempa[0] = tempa[1]; tempa[1] = tempa[2]; tempa[2] = tempa[3]; tempa[3] = t;
      // SubWord
      tempa[0] = sbox[tempa[0]]; tempa[1] = sbox[tempa[1]];
      tempa[2] = sbox[tempa[2]]; tempa[3] = sbox[tempa[3]];
      tempa[0] ^= Rcon[i / 4];
    }
    rk[4*i+0] = rk[4*(i-4)+0] ^ tempa[0];
    rk[4*i+1] = rk[4*(i-4)+1] ^ tempa[1];
    rk[4*i+2] = rk[4*(i-4)+2] ^ tempa[2];
    rk[4*i+3] = rk[4*(i-4)+3] ^ tempa[3];
  }
}

inline void add_round_key(uint8_t round, uint8_t state[16], const uint8_t *rk) {
  for (int i = 0; i < 16; i++) state[i] ^= rk[round * 16 + i];
}
inline void sub_bytes(uint8_t state[16]) { for (int i = 0; i < 16; i++) state[i] = sbox[state[i]]; }
inline void inv_sub_bytes(uint8_t state[16]) { for (int i = 0; i < 16; i++) state[i] = rsbox[state[i]]; }

// state[16] est stocke colonne-major : state[col*4+row]
inline void shift_rows(uint8_t s[16]) {
  uint8_t t;
  // ligne 1 : rotation gauche de 1
  t = s[1]; s[1] = s[5]; s[5] = s[9]; s[9] = s[13]; s[13] = t;
  // ligne 2 : rotation gauche de 2
  t = s[2]; s[2] = s[10]; s[10] = t; t = s[6]; s[6] = s[14]; s[14] = t;
  // ligne 3 : rotation gauche de 3 (= droite de 1)
  t = s[15]; s[15] = s[11]; s[11] = s[7]; s[7] = s[3]; s[3] = t;
}
inline void inv_shift_rows(uint8_t s[16]) {
  uint8_t t;
  t = s[13]; s[13] = s[9]; s[9] = s[5]; s[5] = s[1]; s[1] = t;
  t = s[2]; s[2] = s[10]; s[10] = t; t = s[6]; s[6] = s[14]; s[14] = t;
  t = s[3]; s[3] = s[7]; s[7] = s[11]; s[11] = s[15]; s[15] = t;
}

inline uint8_t xtime(uint8_t x) { return (uint8_t)((x << 1) ^ ((x >> 7) * 0x1b)); }
inline uint8_t gmul(uint8_t a, uint8_t b) {
  uint8_t p = 0;
  for (int i = 0; i < 8; i++) {
    if (b & 1) p ^= a;
    uint8_t hi = a & 0x80;
    a <<= 1;
    if (hi) a ^= 0x1b;
    b >>= 1;
  }
  return p;
}

inline void mix_columns(uint8_t s[16]) {
  for (int c = 0; c < 4; c++) {
    uint8_t *col = s + 4 * c;
    uint8_t a0 = col[0], a1 = col[1], a2 = col[2], a3 = col[3];
    col[0] = (uint8_t)(xtime(a0) ^ (xtime(a1) ^ a1) ^ a2 ^ a3);
    col[1] = (uint8_t)(a0 ^ xtime(a1) ^ (xtime(a2) ^ a2) ^ a3);
    col[2] = (uint8_t)(a0 ^ a1 ^ xtime(a2) ^ (xtime(a3) ^ a3));
    col[3] = (uint8_t)((xtime(a0) ^ a0) ^ a1 ^ a2 ^ xtime(a3));
  }
}
inline void inv_mix_columns(uint8_t s[16]) {
  for (int c = 0; c < 4; c++) {
    uint8_t *col = s + 4 * c;
    uint8_t a0 = col[0], a1 = col[1], a2 = col[2], a3 = col[3];
    col[0] = (uint8_t)(gmul(a0,0x0e) ^ gmul(a1,0x0b) ^ gmul(a2,0x0d) ^ gmul(a3,0x09));
    col[1] = (uint8_t)(gmul(a0,0x09) ^ gmul(a1,0x0e) ^ gmul(a2,0x0b) ^ gmul(a3,0x0d));
    col[2] = (uint8_t)(gmul(a0,0x0d) ^ gmul(a1,0x09) ^ gmul(a2,0x0e) ^ gmul(a3,0x0b));
    col[3] = (uint8_t)(gmul(a0,0x0b) ^ gmul(a1,0x0d) ^ gmul(a2,0x09) ^ gmul(a3,0x0e));
  }
}

inline void set_key(Ctx *ctx, const uint8_t key[16]) { key_expansion(ctx, key); }

inline void encrypt_block(const Ctx *ctx, const uint8_t in[16], uint8_t out[16]) {
  uint8_t s[16];
  memcpy(s, in, 16);
  add_round_key(0, s, ctx->round_key);
  for (int round = 1; round < 10; round++) {
    sub_bytes(s);
    shift_rows(s);
    mix_columns(s);
    add_round_key(round, s, ctx->round_key);
  }
  sub_bytes(s);
  shift_rows(s);
  add_round_key(10, s, ctx->round_key);
  memcpy(out, s, 16);
}

inline void decrypt_block(const Ctx *ctx, const uint8_t in[16], uint8_t out[16]) {
  uint8_t s[16];
  memcpy(s, in, 16);
  add_round_key(10, s, ctx->round_key);
  for (int round = 9; round >= 1; round--) {
    inv_shift_rows(s);
    inv_sub_bytes(s);
    add_round_key(round, s, ctx->round_key);
    inv_mix_columns(s);
  }
  inv_shift_rows(s);
  inv_sub_bytes(s);
  add_round_key(0, s, ctx->round_key);
  memcpy(out, s, 16);
}

