#!/usr/bin/env python3
"""Generate the packages ../../../code/device_ecoflow_<model>.yaml (every entity of a model) from registers.py.

Usage:  python3 -I gen_yaml.py
Entity names are written unquoted as `name: ${name}_${ecoflow_name}_<key>` (the author's convention).
The output platform and the number / select / switch controls that move power are written commented out or inert:
see the header of the generated file.
"""
import importlib.util
from pathlib import Path

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("registers", HERE.parent / "registers.py")
registers = importlib.util.module_from_spec(spec)
spec.loader.exec_module(registers)

OUT = HERE.parent.parent.parent / "code"
READ_PLATFORMS = ("sensor", "text_sensor", "binary_sensor")
WRITE_PLATFORMS = ("switch", "number", "select")


def nest(specs):
    tree = {}
    for s in specs.values():
        node = tree
        for part in s["path"][:-1]:
            node = node.setdefault(part, {})
        node[s["path"][-1]] = s
    return tree


def emit(tree, indent, lines):
    for name, child in tree.items():
        pad = " " * indent
        lines.append(f"{pad}{name}:")
        if "register" in child:
            key = "_".join(p for p in child["path"] if p != "packs")
            lines.append(f"{pad}  name: ${{name}}_${{ecoflow_name}}_{key}")
        else:
            emit(child, indent + 2, lines)


def block(platform, data):
    lines = [f"{platform}:", "  - platform: ecoflow_stream", "    ecoflow_stream_id: ${ecoflow_id}"]
    emit(nest(data["specs"][platform]), 4, lines)
    if platform == "binary_sensor":
        lines += ["    modbus_connection:", "      name: ${name}_${ecoflow_name}_modbus_connection"]
    if platform == "switch":
        lines += ["    heartbeat:", "      name: ${name}_${ecoflow_name}_heartbeat"]
    return lines + [""]


def main():
    for model, data in registers.REGISTERS.items():
        title = registers.MODEL_NAMES[model]
        lines = [
            f"# EcoFlow {title}: every entity of the `{model}` register map (GENERATED by",
            "# components/ecoflow_stream/tools/gen_yaml.py).",
            "# Package vars: ecoflow_name, ecoflow_id, ecoflow_modbus_controller (id of the modbus bus),",
            "# ecoflow_modbus_address, ecoflow_fast_update_interval, ecoflow_slow_update_interval.",
            "#",
            "# READ ONLY as shipped. The controls are in the commented block at the end: uncomment them once the readings",
            "# have been checked against the EcoFlow app (it needs \"View and control\" there).",
            "",
            "external_components:",
            "  - source: github://SeByDocKy/myESPhome",
            "    components: [ecoflow_stream]",
            "    refresh: 10s",
            "",
            "modbus_controller:",
            "  - id: ${ecoflow_name}_fast_modbus_controller",
            "    address: ${ecoflow_modbus_address}",
            "    modbus_id: ${ecoflow_modbus_controller}",
            "    update_interval: ${ecoflow_fast_update_interval}",
            "  - id: ${ecoflow_name}_slow_modbus_controller",
            "    address: ${ecoflow_modbus_address}",
            "    modbus_id: ${ecoflow_modbus_controller}",
            "    update_interval: ${ecoflow_slow_update_interval}",
            "",
            "ecoflow_stream:",
            "  id: ${ecoflow_id}",
            f"  model: {model}",
            "  modbus_controller_id: ${ecoflow_name}_fast_modbus_controller",
            "  slow_modbus_controller_id: ${ecoflow_name}_slow_modbus_controller",
            "",
        ]
        for platform in READ_PLATFORMS:
            lines += block(platform, data)
        controls = []
        for platform in WRITE_PLATFORMS:
            controls += block(platform, data)
        lines += [f"# {line}".rstrip() for line in controls]
        path = OUT / f"device_ecoflow_{model}.yaml"
        path.write_text("\n".join(lines).rstrip() + "\n")
        print("wrote", path)


if __name__ == "__main__":
    main()
