#!/usr/bin/env python3
"""Generate the packages ../../../code/device_ecoflow_<model>.yaml (every entity of a model) from registers.py.

Usage:  python3 -I gen_yaml.py
Entity names are written unquoted as `name: ${name}_${ecoflow_name}_<key>` (the author's convention).
The output platform and the number / select / switch controls that move power are written commented out or inert:
see the header of the generated file.
"""
import importlib.util
from pathlib import Path

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("registers", HERE.parent / "registers.py")
registers = importlib.util.module_from_spec(spec)
spec.loader.exec_module(registers)

OUT = HERE.parent.parent.parent / "code"
READ_PLATFORMS = ("sensor", "text_sensor", "binary_sensor")
WRITE_PLATFORMS = ("switch", "number", "select")


def nest(specs):
    tree = {}
    for s in specs.values():
        node = tree
        for part in s["path"][:-1]:
            node = node.setdefault(part, {})
        node[s["path"][-1]] = s
    return tree


def emit(tree, indent, lines):
    for name, child in tree.items():
        pad = " " * indent
        lines.append(f"{pad}{name}:")
        if "register" in child:
            key = "_".join(p for p in child["path"] if p != "packs")
            lines.append(f"{pad}  name: ${{name}}_${{ecoflow_name}}_{key}")
        else:
            emit(child, indent + 2, lines)


def block(platform, data):
    lines = [f"{platform}:", "  - platform: ecoflow_stream", "    ecoflow_stream_id: ${ecoflow_id}"]
    emit(nest(data["specs"][platform]), 4, lines)
    if platform == "binary_sensor":
        lines += ["    modbus_connection:", "      name: ${name}_${ecoflow_name}_modbus_connection"]
    if platform == "switch":
        lines += ["    heartbeat:", "      name: ${name}_${ecoflow_name}_heartbeat"]
    return lines + [""]


# Entities of the single package which also get an id, to be used from the main YAML
IDS = {
    ("sensor", "battery_soc"), ("sensor", "battery_power"), ("sensor", "ac_grid_power"),
    ("sensor", "ac_home_power"), ("binary_sensor", "system_master"), ("select", "control_point"),
}


def generic_package():
    """code/device_ecoflow_stream.yaml: both models, every entity and the outputs, all active."""
    data = next(iter(registers.REGISTERS.values()))
    assert all(d == data for d in registers.REGISTERS.values()), "the models differ: one package per model"
    lines = [
        "# EcoFlow STREAM 5000 / STREAM AC 5000: every entity, control and output (GENERATED by",
        "# components/ecoflow_stream/tools/gen_yaml.py).",
        "# Package vars:",
        "#   ecoflow_name, ecoflow_id",
        "#   ecoflow_model: stream5000 or stream_ac5000",
        "#   ecoflow_modbus_controller (id of the modbus bus), ecoflow_modbus_address",
        "#   ecoflow_fast_update_interval, ecoflow_slow_update_interval",
        "#   ecoflow_charge_sign: negative or positive, sign of the target power which charges the battery.",
        "#     NOT documented by EcoFlow: check it with a small value before using the outputs.",
        "#   ecoflow_battery_power_charge_sign (optional, default positive): sign of the device battery power",
        "#     while charging.",
        "# Sign convention of this package: positive = charge, negative = discharge.",
        "#",
        "# The heartbeat switch starts OFF: turn it on to take control of the battery (needs \"View and control\" in",
        "# the EcoFlow app). Without a heartbeat for 60 s the battery returns to its own energy management.",
        "# Ids usable from the main YAML:",
        "#   ${ecoflow_name}_ecoflow_charge_power, ${ecoflow_name}_ecoflow_discharge_power (outputs),",
        "#   ${ecoflow_name}_heartbeat, ${ecoflow_name}_control_point, ${ecoflow_name}_battery_soc,",
        "#   ${ecoflow_name}_battery_power, ${ecoflow_name}_ac_grid_power, ${ecoflow_name}_ac_home_power,",
        "#   ${ecoflow_name}_system_master",
        "",
        "defaults:",
        "  ecoflow_battery_power_charge_sign: positive",
        "",
        "external_components:",
        "  - source: github://SeByDocKy/myESPhome",
        "    components: [ecoflow_stream]",
        "    refresh: 10s",
        "",
        "modbus_controller:",
        "  - id: ${ecoflow_name}_fast_modbus_controller",
        "    address: ${ecoflow_modbus_address}",
        "    modbus_id: ${ecoflow_modbus_controller}",
        "    update_interval: ${ecoflow_fast_update_interval}",
        "  # Slow-changing entities (versions, serial numbers, counters, settings) are polled less often",
        "  - id: ${ecoflow_name}_slow_modbus_controller",
        "    address: ${ecoflow_modbus_address}",
        "    modbus_id: ${ecoflow_modbus_controller}",
        "    update_interval: ${ecoflow_slow_update_interval}",
        "",
        "ecoflow_stream:",
        "  id: ${ecoflow_id}",
        "  model: ${ecoflow_model}",
        "  modbus_controller_id: ${ecoflow_name}_fast_modbus_controller",
        "  slow_modbus_controller_id: ${ecoflow_name}_slow_modbus_controller",
        "  charge_sign: ${ecoflow_charge_sign}",
        "  battery_power_charge_sign: ${ecoflow_battery_power_charge_sign}",
        "  # Point driven by the outputs: battery, inverter or grid_port",
        "  control_point: battery",
        "  # false: select the control point yourself; true: written before a setpoint when it differs",
        "  auto_control_point: false",
        "  # The battery reports its own maximum power. Set these only to limit it further.",
        "  # max_charge_power: 800",
        "  # max_discharge_power: 800",
        "  heartbeat_interval: 20s",
        "  setpoint_refresh: 0ms",
        "",
    ]
    for platform in READ_PLATFORMS + WRITE_PLATFORMS:
        out = []
        for line in block(platform, data):
            out.append(line)
            key = line.strip().removeprefix("name: ${name}_${ecoflow_name}_")
            pad = line[: len(line) - len(line.lstrip())]
            if line.strip().startswith("name:") and (platform, key) in IDS:
                out.insert(len(out) - 1, f"{pad}id: ${{ecoflow_name}}_{key}")
            if platform == "switch" and key == "heartbeat" and line.strip().startswith("name:"):
                out += [f"{pad}id: ${{ecoflow_name}}_heartbeat", f"{pad}restore_mode: RESTORE_DEFAULT_OFF"]
        lines += out
    lines += [
        "output:",
        "  - platform: ecoflow_stream",
        "    ecoflow_stream_id: ${ecoflow_id}",
        "    charge_power:",
        "      id: ${ecoflow_name}_ecoflow_charge_power",
        "    discharge_power:",
        "      id: ${ecoflow_name}_ecoflow_discharge_power",
    ]
    path = OUT / "device_ecoflow_stream.yaml"
    path.write_text("\n".join(lines).rstrip() + "\n")
    print("wrote", path)


def main():
    for model, data in registers.REGISTERS.items():
        title = registers.MODEL_NAMES[model]
        lines = [
            f"# EcoFlow {title}: every entity of the `{model}` register map (GENERATED by",
            "# components/ecoflow_stream/tools/gen_yaml.py).",
            "# Package vars: ecoflow_name, ecoflow_id, ecoflow_modbus_controller (id of the modbus bus),",
            "# ecoflow_modbus_address, ecoflow_fast_update_interval, ecoflow_slow_update_interval.",
            "#",
            "# READ ONLY as shipped. The controls are in the commented block at the end: uncomment them once the readings",
            "# have been checked against the EcoFlow app (it needs \"View and control\" there).",
            "",
            "external_components:",
            "  - source: github://SeByDocKy/myESPhome",
            "    components: [ecoflow_stream]",
            "    refresh: 10s",
            "",
            "modbus_controller:",
            "  - id: ${ecoflow_name}_fast_modbus_controller",
            "    address: ${ecoflow_modbus_address}",
            "    modbus_id: ${ecoflow_modbus_controller}",
            "    update_interval: ${ecoflow_fast_update_interval}",
            "  - id: ${ecoflow_name}_slow_modbus_controller",
            "    address: ${ecoflow_modbus_address}",
            "    modbus_id: ${ecoflow_modbus_controller}",
            "    update_interval: ${ecoflow_slow_update_interval}",
            "",
            "ecoflow_stream:",
            "  id: ${ecoflow_id}",
            f"  model: {model}",
            "  modbus_controller_id: ${ecoflow_name}_fast_modbus_controller",
            "  slow_modbus_controller_id: ${ecoflow_name}_slow_modbus_controller",
            "",
        ]
        for platform in READ_PLATFORMS:
            lines += block(platform, data)
        controls = []
        for platform in WRITE_PLATFORMS:
            controls += block(platform, data)
        lines += [f"# {line}".rstrip() for line in controls]
        path = OUT / f"device_ecoflow_{model}.yaml"
        path.write_text("\n".join(lines).rstrip() + "\n")
        print("wrote", path)


if __name__ == "__main__":
    main()
    generic_package()
