#!/usr/bin/env python3
"""Generate the example packages ../../../code/device_bluetti_<model>.yaml (every entity of a model) from registers.py.

Usage:  python gen_yaml.py
Entity names are written unquoted as `name: ${name}_${bluetti_name}_<key>` (the author's convention).
"""
import importlib.util
from pathlib import Path

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("registers", HERE.parent / "registers.py")
registers = importlib.util.module_from_spec(spec)
spec.loader.exec_module(registers)

OUT = HERE.parent.parent.parent / "code"
PLATFORMS = ("sensor", "text_sensor", "binary_sensor")


def entity_name(path):
    parts = [p for p in path if p not in ("packs",)]
    return "_".join(parts)


def nest(specs):
    tree = {}
    for key, s in specs.items():
        node = tree
        for part in s["path"][:-1]:
            node = node.setdefault(part, {})
        node[s["path"][-1]] = s
    return tree


def emit(tree, indent, lines):
    for name, child in tree.items():
        pad = " " * indent
        if "register" in child:  # a leaf (a spec)
            lines.append(f"{pad}{name}:")
            lines.append(f"{pad}  name: ${{name}}_${{bluetti_name}}_{entity_name(child['path'])}")
        else:
            lines.append(f"{pad}{name}:")
            emit(child, indent + 2, lines)


def main():
    for model, data in registers.REGISTERS.items():
        title = registers.MODEL_NAMES[model]
        lines = [
            f"# BLUETTI {title}: every entity of the `{model}` register map (GENERATED by components/bluetti/tools/gen_yaml.py).",
            "# Package vars: bluetti_name, bluetti_id, bluetti_modbus_controller (id of the modbus bus), bluetti_modbus_address,",
            "# bluetti_fast_update_interval, bluetti_slow_update_interval. Keep the entities you need.",
            "",
            "external_components:",
            "  - source: github://SeByDocKy/myESPhome",
            "    components: [bluetti]",
            "    refresh: 10s",
            "",
            "modbus_controller:",
            "  - id: ${bluetti_name}_fast_modbus_controller",
            "    address: ${bluetti_modbus_address}",
            "    modbus_id: ${bluetti_modbus_controller}",
            "    update_interval: ${bluetti_fast_update_interval}",
            "  # Slow-changing entities (versions, serial numbers, counters, settings) are polled less often",
            "  - id: ${bluetti_name}_slow_modbus_controller",
            "    address: ${bluetti_modbus_address}",
            "    modbus_id: ${bluetti_modbus_controller}",
            "    update_interval: ${bluetti_slow_update_interval}",
            "",
            "bluetti:",
            "  id: ${bluetti_id}",
            f"  model: {model}",
            "  modbus_controller_id: ${bluetti_name}_fast_modbus_controller",
            "  slow_modbus_controller_id: ${bluetti_name}_slow_modbus_controller",
            "",
        ]
        for platform in PLATFORMS:
            lines.append(f"{platform}:")
            lines.append("  - platform: bluetti")
            lines.append("    bluetti_id: ${bluetti_id}")
            tree = nest(data["specs"][platform])
            body = []
            emit(tree, 4, body)
            lines += body
            if platform == "binary_sensor":
                lines.append("    modbus_connection:")
                lines.append("      name: ${name}_${bluetti_name}_modbus_connection")
            lines.append("")
        path = OUT / f"device_bluetti_{model}.yaml"
        path.write_text("\n".join(lines).rstrip() + "\n")
        print("wrote", path)


if __name__ == "__main__":
    main()
